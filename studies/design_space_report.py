def ok(rows):
    return [r for r in rows if "error" not in r and "metrics" in r]


def label(r):
    c = r["config"]
    x = f"ud {c['v_underdrive']:g} V" if c["arch"] != "TSWO" else f"I_buf {c['i_buf'] * 1e9:g} nA"
    return (f"{NAMES[c['arch']]}, W {c['wn']:g} µm, C {c['c_node'] * 1e12:g} pF, ESD {c['esd_area']:g} µm², {x}")


BUF_POWER = {"value": 0.0}   # static power of the real OTA (TSWO, 1 nA), set in main()


def power(r, key=REF):
    """Power per electrode to keep 99.9 % (refresh at the hold time) plus static power. The ideal-
    buffer designs (TSWB, NTB) are charged the measured static power of the real OTA (TSWO, 1 nA)."""
    t = r["metrics"][key]["hold_time"]
    if t <= 0:
        return np.inf
    p_static = r["energy"]["p_static"]
    if r["config"]["arch"] in ("TSWB", "NTB"):
        p_static = BUF_POWER["value"]
    return r["energy"]["e_refresh"] / t + p_static


def pareto(rows, fx, fy, minimize_y=True):
    """Non-dominated rows: smaller fx, and smaller (or larger) fy."""
    pts = sorted(rows, key=lambda r: (fx(r), fy(r) if minimize_y else -fy(r)))
    front, best = [], np.inf
    for r in pts:
        y = fy(r) if minimize_y else -fy(r)
        if y < best:
            front.append(r)
            best = y
    return front


def fmt_t(t):
    if not np.isfinite(t) or t <= 0:
        return "0"
    for unit, sc in (("s", 1), ("ms", 1e-3), ("µs", 1e-6), ("ns", 1e-9)):
        if t >= sc:
            return f"{t / sc:.3g} {unit}"
    return f"{t:.2g} s"


def fmt_p(p):
    if not np.isfinite(p):
        return "—"
    for unit, sc in (("µW", 1e-6), ("nW", 1e-9), ("pW", 1e-12), ("fW", 1e-15)):
        if p >= sc:
            return f"{p / sc:.3g} {unit}"
    return f"{p:.2g} W"


def best_per_arch(grid, key=REF, esd=None, c_node=None):
    out = {}
    for r in grid:
        c = r["config"]
        if (esd is not None and c["esd_area"] != esd) or (c_node is not None and abs(c["c_node"] - c_node) > 1e-18):
            continue
        a = c["arch"]
        if a not in out or r["metrics"][key]["n_flat"] > out[a]["metrics"][key]["n_flat"]:
            out[a] = r
    return out


def comp_stats(cosim):
    rows = {"independent": [], "coherent": [], "phase_additive": []}
    for d in cosim:
        if "error" in d:
            continue
        for p in d["points"]:
            for c in p["composition"]:
                if c["f_real"] < 1e-6:
                    continue
                for k in rows:
                    if f"f_{k}" in c:
                        rows[k].append(c[f"f_{k}"] / c["f_real"] - 1)
    return {k: (float(np.median(np.abs(v))), float(np.max(np.abs(v))), len(v)) for k, v in rows.items() if v}


def headline(res):
    grid = ok(res["grid"])
    b = best_per_arch(grid, esd=0.0, c_node=1e-12)
    b_esd = best_per_arch(grid, esd=100.0, c_node=1e-12)
    out = {}
    for a, r in b.items():
        m = r["metrics"][REF]
        out[a] = {"n_flat": m["n_flat"], "n_tree": m["n_tree"], "hold": m["hold_time"],
                  "n_flat_esd": b_esd[a]["metrics"][REF]["n_flat"] if a in b_esd else np.nan,
                  "power": power(r), "area": r["area"]["total"], "label": label(r)}
    return out


