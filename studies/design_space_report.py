          "DAC code is corrected with a linear fit of the settled level, and the CZ amplitude with the "
          "coupling k measured at the electrode's own bias. *Global k*: one k, calibrated at 0.9 V, for "
          "all electrodes. Droop is not included in this table (see section 2).", "",
