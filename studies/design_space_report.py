def fig_cosim(res, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(1, 3, figsize=(16, 4.8))
    a0 = ax[0]
    for d in res["cosim"]:
        if "error" in d or d["slope"] != 10:
            continue
        p = d["points"][0]
        t = np.array(d["t_trace"]) * 1e9
        a0.plot(t, (np.array(p["dv_trace"]) - p["static"]) * 1e3, label=f"{d['name']} ({p['target']:g} V)")
    a0.set(xlabel="time in the CZ (ns)", ylabel="barrier error minus its static part (mV)",
           title="(a) real waveform: pulse distortion and mid-gate crosstalk")
    a0.legend(fontsize=6)
    a1 = ax[1]
    ds = [d for d in res["cosim"] if "error" not in d and d["slope"] == 10]
    x = np.arange(len(ds))
    a1.bar(x - 0.2, [max(p["infidelity"] for p in d["points"]) for d in ds], 0.4, label="per-electrode k")
    a1.bar(x + 0.2, [max(p["infidelity_global_k"] for p in d["points"]) for d in ds], 0.4, label="one global k")
    a1.set_yscale("log")
    a1.axhline(1e-3, color="k", lw=0.8)
    a1.axhline(1e-4, color="k", ls="--", lw=0.8)
    a1.set_xticks(x, [d["name"].replace(", ", ",\n") for d in ds], fontsize=6, rotation=35, ha="right")
    a1.set(ylabel="worst 1 − F over held voltage (s = 10)", title="(b) co-simulated infidelity, no droop")
    a1.legend(fontsize=7)
    a2 = ax[2]
    for k, mk in (("independent", "x"), ("coherent", "+"), ("phase_additive", "o")):
        xs, ys = [], []
        for d in res["cosim"]:
            if "error" in d:
                continue
            for p in d["points"]:
                for c in p["composition"]:
                    if f"f_{k}" in c:
                        xs.append(c["f_real"])
                        ys.append(c[f"f_{k}"])
        a2.loglog(xs, ys, mk, ms=4, alpha=0.7, mfc="none" if mk == "o" else None, label=k.replace("_", "-"))
    lim = [1e-6, 1e-2]
    a2.plot(lim, lim, "k-", lw=0.8)
    a2.set(xlim=lim, ylim=lim, xlabel="1 − F, real waveform + droop offset", ylabel="1 − F, combination rule",
           title="(c) deterministic errors add in phase")
    a2.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(path, dpi=150)


def fig_pareto(res, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    grid = ok(res["grid"])
    fig, ax = plt.subplots(1, 3, figsize=(16, 4.8))
    panels = ((lambda r: r["metrics"][REF]["hold_time"], False, "hold time at 99.9 % (s)", "(a) hold time"),
              (lambda r: r["infidelity_1ms"], True, "added 1 − F at a 1 ms refresh period", "(b) fidelity"),
              (power, True, "power per electrode at 99.9 % (W)", "(c) power (refresh + static)"))
    for a_, (fy, mn, yl, ti) in zip(ax, panels):
        for arch in NAMES:
            rows = [r for r in grid if r["config"]["arch"] == arch and np.isfinite(fy(r)) and fy(r) > 0]
            if rows:
                a_.scatter([r["area"]["total"] for r in rows], [fy(r) for r in rows], s=8, alpha=0.5,
                           color=COLORS[arch], label=NAMES[arch])
        front = pareto([r for r in grid if np.isfinite(fy(r)) and fy(r) > 0], lambda r: r["area"]["total"], fy, mn)
        a_.step([r["area"]["total"] for r in front], [fy(r) for r in front], "k-", where="post", lw=1.2,
                label="Pareto front")
        a_.set_xscale("log")
        a_.set_yscale("log")
        a_.set(xlabel="area per electrode (µm², estimate)", ylabel=yl, title=ti + " against area, s = 10 dec/V")
    ax[1].axhline(1e-3, color="grey", lw=0.8)
    ax[0].legend(fontsize=6, ncol=2)
    fig.tight_layout()
    fig.savefig(path, dpi=150)


def fig_scaling(res, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    grid = ok(res["grid"])
    fig, ax = plt.subplots(1, 3, figsize=(16, 4.8))
    cs = res["settings"]["grid"]["c_node"]
    a0 = ax[0]
    for arch in NAMES:
        xs, flat, tree = [], [], []
        for c in cs:
            b = best_per_arch([r for r in grid if r["config"]["arch"] == arch], esd=0.0, c_node=c)
            if arch in b:
                xs.append(c * 1e12)
                flat.append(b[arch]["metrics"][REF]["n_flat"])
                tree.append(b[arch]["metrics"][REF]["n_tree"])
        if xs:
            a0.loglog(xs, np.maximum(flat, 0.5), "o-", color=COLORS[arch], label=NAMES[arch])
            a0.loglog(xs, np.maximum(tree, 0.5), ":", color=COLORS[arch])
    for (k, v), ls in zip(LIT.items(), ("--", "-.")):
        a0.axhline(v, color="k", ls=ls, lw=0.8, label=k)
    a0.set(xlabel="C_node (pF)", ylabel="electrodes per DAC line at 99.9 %",
           title="(a) s = 10, no ESD; solid flat line, dotted tree", ylim=(0.5, None))
    a0.legend(fontsize=6)
    a1 = ax[1]
    keys = ("s3.87_t0.001", "s10_t0.001", "s33.69_t0.001", "s10_t0.0001", "s10_t0.001_idle")
    labs = ("3.87, 99.9 %", "10, 99.9 %", "33.7, 99.9 %", "10, 99.99 %", "10, 99.9 %, 1 µs idle")
    b = best_per_arch(grid, esd=0.0, c_node=1e-12)
    archs = sorted(b, key=lambda a: -b[a]["metrics"][REF]["n_flat"])
    x = np.arange(len(archs))
    for j, (k, lb) in enumerate(zip(keys, labs)):
        a1.bar(x + (j - 2) * 0.16, [max(b[a]["metrics"][k]["n_flat"], 0.5) for a in archs], 0.16, label=lb)
    a1.set_yscale("log")
    a1.set_xticks(x, [NAMES[a].replace(", ", ",\n") for a in archs], fontsize=7, rotation=35, ha="right")
    a1.set(ylabel="electrodes per flat line", title="(b) slope, target and idle drift (1 pF, no ESD)")
    a1.legend(fontsize=6)
    a2 = ax[2]
    for arch in NAMES:
        rows = [r for r in grid if r["config"]["arch"] == arch and r["metrics"][REF]["n_tree"] > 0]
        if rows:
            fom = [r["summary"]["leakage_max"] * r["cell"]["tau_node"] / r["summary"]["c_eff"] for r in rows]
            a2.loglog(fom, [r["metrics"][REF]["n_tree"] for r in rows], ".", color=COLORS[arch], alpha=0.6,
                      label=NAMES[arch])
    f = np.geomspace(1e-13, 1e-5, 20)
    bd = 2 * (res["spec"][REF] * 0.9)
    a2.loglog(f, bd / (f * np.log(bd / (0.1 * res["spec"][REF]) + 1)), "k--", lw=0.8,
              label="N = 2 b / (I_leak R_on ln), settling-limited")
    a2.set(xlabel="I_leak · R_on = I_leak · τ_node / C_eff (V)", ylabel="electrodes per tree line",
           title="(c) the switch figure of merit I_leak · R_on")
    a2.legend(fontsize=6)
    fig.tight_layout()
    fig.savefig(path, dpi=150)


