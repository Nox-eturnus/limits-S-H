"""Tables and figure of the single-cell characterisation, from results/cells.json.

Run:  python studies/cells_report.py      (seconds; writes results/cells.md and results/cells.png)
"""
import json
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parents[1] / "results"
ARCH_NAMES = {"NSW": "1 NMOS", "TG": "2 TG", "TGD": "3 TG + dummies", "BOOT": "4 bootstrapped NMOS",
              "CLK": "5 charge-locked (TG + C_pulse)", "TSW": "6 thick-oxide T-switch",
              "TGH": "7 TG, high-V_T PMOS", "TSWB": "8 T-switch, buffered middle (thick)",
              "NTB": "9 T-switch, buffered middle (thin)"}
SLOT = 1e-6            # refresh slot per electrode for the gates-per-line illustration
COMP_RESIDUALS = (0.1, 0.01)   # fraction of the droop left after feed-forward compensation (assumed)
SLOPES = ("3.87", "10", "33.69")


def mv(x):
    return f"{x * 1e3:.3g}"


def uv(x):
    return f"{x * 1e6:.3g}"


def corner_point(a, corner):
    return next(r for r in a["sweeps"]["corner"] if r["config"]["corner"] == corner)


def write_md(res, path):
    L = ["# Single-cell results (generated by studies/cells_report.py; do not edit)", "",
         "Nominal point: W_n = 1 µm (TSW: thick oxide, 1 µm, L = 0.5 µm, 3.3 V gate drive), "
         "C_node = 1 pF, ESD pair 100 µm² each, clock edges 200 ps, tt, 27 °C, held voltages "
         "0.3-1.5 V (NSW: 0.3-0.9 V). SKY130 room-temperature models.", "",
         "## 1. Measured error terms at the nominal point", "",
         "| architecture | C_eff (pF) | pedestal mean (mV) | pedestal span (mV) | residual after linear cal (µV) "
         "| MC σ (µV) | feedthrough (×1e-6) | refresh glitch peak (mV) | droop tt (V/s) | droop leak corner (V/s) "
         "| kT/C at 4 K (µV) |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for k, a in res["archs"].items():
        s = a["nominal"]["summary"]
        lk = corner_point(a, "leak")["summary"]
        L.append(f"| {ARCH_NAMES[k]} | {s['c_eff'] * 1e12:.3g} | {mv(s['pedestal_mean'])} | "
                 f"{mv(s['pedestal_span'])} | {uv(s['pedestal_linear_residual'])} | "
                 f"{uv(a['mc']['pedestal_sigma_max'])} | {s['feedthrough_max'] * 1e6:.3g} | "
                 f"{mv(s['refresh_glitch_max'])} | {s['droop_max']:.3g} | {lk['droop_max']:.3g} | "
                 f"{uv(s['ktc_rms_4k'])} |")
    L += ["", "## 2. Against the error budget (J + Stark), nominal point", "",
          "Margin = spec / measured (> 1 passes). Hold time = static spec / droop (tt, room "
          "temperature; see section 4 for the leak corner). Refresh and crosstalk: the added "
          "infidelity of the measured waveform, ✓ if within the target.", ""]
    for tgt in ("0.001", "0.0001"):
        L += [f"### Target 1 - F = {tgt}", "",
              "| architecture | s (dec/V) | residual margin | shared-cal margin | kT/C 4 K margin | "
              "hold time tt (s) | refresh during gate | neighbour crosstalk |",
              "|---|---|---|---|---|---|---|---|"]
        for k, a in res["archs"].items():
            for s in SLOPES:
                key = f"s{s}_t{tgt}"
                j = a["nominal"]["judge"][key]
                L.append(f"| {ARCH_NAMES[k]} | {s} | {j['residual_margin']:.3g} | "
                         f"{a['mc']['shared_cal_margin'][key]:.3g} | {j['ktc4k_margin']:.3g} | "
                         f"{j['hold_time_s']:.3g} | {j['refresh_infidelity']:.1e} "
                         f"{'✓' if j['refresh_pass'] else '✗'} | {j['crosstalk_infidelity']:.1e} "
                         f"{'✓' if j['crosstalk_pass'] else '✗'} |")
        L.append("")
    L += ["## 3. Sweeps (one parameter at a time around the nominal point)", ""]
    labels = {"wn": ("W_n (µm)", 1), "c_node": ("C_node (pF)", 1e12), "t_edge": ("edge (ns)", 1e9),
              "corner": ("corner", None), "temp": ("T (°C)", 1), "esd_area": ("ESD area (µm²)", 1),
              "v_underdrive": ("underdrive (V)", 1), "l": ("L (µm)", 1), "v_os": ("buffer offset (mV)", 1e3)}
    for par, (lab, sc) in labels.items():
        L += [f"### {lab}", "",
              "| architecture | " + lab + " | span (mV) | residual (µV) | feedthrough (×1e-6) | "
              "refresh peak (mV) | droop (V/s) | C_eff (pF) | refresh, s = 10, 1e-3 |",
              "|---|---|---|---|---|---|---|---|---|"]
        for k, a in res["archs"].items():
            for r in a["sweeps"].get(par, []):
                v = r["config"][par]
                vs = v if sc is None else f"{v * sc:g}"
                if "error" in r:
                    L.append(f"| {ARCH_NAMES[k]} | {vs} | simulation failed | | | | | | |")
                    continue
                s = r["summary"]
                j = r["judge"]["s10_t0.001"]
                L.append(f"| {ARCH_NAMES[k]} | {vs} | {mv(s['pedestal_span'])} | "
                         f"{uv(s['pedestal_linear_residual'])} | {s['feedthrough_max'] * 1e6:.3g} | "
                         f"{mv(s['refresh_glitch_max'])} | {s['droop_max']:.3g} | {s['c_eff'] * 1e12:.3g} | "
                         f"{j['refresh_infidelity']:.1e} |")
        L.append("")
    L += ["## 4. Hold time at the leak corner (static spec / droop, room temperature)", "",
          "| architecture | s = 3.87, 1e-3 | s = 10, 1e-3 | s = 33.69, 1e-3 | s = 33.69, 1e-4 |",
          "|---|---|---|---|---|"]
    for k, a in res["archs"].items():
        j = corner_point(a, "leak")["judge"]
        L.append(f"| {ARCH_NAMES[k]} | " + " | ".join(
            f"{j[key]['hold_time_s']:.3g} s" for key in
            ("s3.87_t0.001", "s10_t0.001", "s33.69_t0.001", "s33.69_t0.0001")) + " |")
    L += mitigation_section(res)
    L += ["", f"Runtime of characterise.py: {res['runtime_s'] / 60:.0f} min.", ""]
    path.write_text("\n".join(L), encoding="utf-8")


def ladder(res, key="s10_t0.001"):
    """Hold time per architecture: nominal -> best circuit (no ESD, best underdrive) -> centred ->
    feed-forward compensated, leaving a fraction u of the droop (assumed, COMP_RESIDUALS).

    The compensation residual is an assumption, not a measurement: the PDK's diode models carry no
    mismatch and room-temperature leakage drift says nothing about 4 K, so neither the Monte Carlo
    spread nor the 17-37 C sweep is a valid estimate of u."""
    out = {}
    for k, a in res["archs"].items():
        spec = res["spec"][key]["static"]
        nom = a["nominal"]["summary"]["droop_max"]
        c = a.get("combined")
        best = c["summary"]["droop_max"] if c else np.nan
        row = {"nominal": spec / nom, "best": spec / best, "centred": 2 * spec / best,
               "best_config": {kk: c["config"][kk] for kk in ("esd_area", "v_underdrive")} if c else None,
               "nominal_droop": nom, "best_droop": best}
        for u in COMP_RESIDUALS:
            row[f"comp_{u:g}"] = spec / (u * best)
        out[k] = row
    return out


def mitigation_section(res):
    L = ["", "## 5. Droop mitigation ladder (s = 10 dec/V, 99.9 %, room temperature, 1 pF)", "",
         "Hold time = static spec / droop. *Best circuit*: no ESD on the hold node (internal node, no "
         "pad) and the better of 0 / 0.3 V gate underdrive. *Centred*: each sample pre-offset by half "
         "the expected droop (2×). *Compensated*: the expected droop is subtracted (feed-forward, from "
         "time since refresh), leaving a fraction u of it; u is an assumption (10 %, 1 %), not a "
         "measurement. Electrodes per DAC line: an upper bound from droop alone, centred hold time / "
         f"{SLOT * 1e6:g} µs slot.", "",
         "| architecture | droop nominal (V/s) | droop best (V/s) | best config | hold nominal | hold best | "
         "centred | compensated, u = 10 % | compensated, u = 1 % | electrodes / line (centred) |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for k, r in ladder(res).items():
        cfg = r["best_config"]
        cs = f"ESD {cfg['esd_area']:g}, ud {cfg['v_underdrive']:g} V" if cfg else "—"
        L.append(f"| {ARCH_NAMES[k]} | {r['nominal_droop']:.3g} | {r['best_droop']:.3g} | {cs} | "
                 f"{fmt_t(r['nominal'])} | {fmt_t(r['best'])} | {fmt_t(r['centred'])} | "
                 f"{fmt_t(r['comp_0.1'])} | {fmt_t(r['comp_0.01'])} | {r['centred'] / SLOT:.2g} |")
    return L


def fmt_t(t):
    if not np.isfinite(t):
        return "—"
    for unit, sc in (("s", 1), ("ms", 1e-3), ("µs", 1e-6), ("ns", 1e-9)):
        if t >= sc:
            return f"{t / sc:.3g} {unit}"
    return f"{t:.2g} s"


def plot(res, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(3, 2, figsize=(11.5, 12.5))
    spec = res["spec"]
    a0 = ax[0, 0]
    for k, a in res["archs"].items():
        v = np.linspace(0.3, 0.9 if k == "NSW" else 1.5, len(a["nominal"]["pedestal_mv"]))
        a0.plot(v, a["nominal"]["pedestal_mv"], marker="o", label=ARCH_NAMES[k])
    a0.axhline(0, color="grey", lw=0.5)
    a0.set(xlabel="held voltage (V)", ylabel="pedestal (mV)", title="(a) pedestal, C_node = 1 pF")
    a0.legend(fontsize=7)

    a1 = ax[0, 1]
    for k, a in res["archs"].items():
        rows = [r for r in a["sweeps"]["c_node"] if "error" not in r]
        a1.loglog([r["summary"]["c_eff"] * 1e12 for r in rows],
                  [max(r["summary"]["pedestal_linear_residual"], 1e-9) * 1e6 for r in rows],
                  marker="o", label=ARCH_NAMES[k])
    for key, ls in (("s33.69_t0.0001", "--"), ("s33.69_t0.001", "-")):
        a1.axhline(spec[key]["static"] * 1e6, color="k", ls=ls, lw=0.8,
                   label=f"static spec, s = 33.7, {key.split('_t')[1]}")
    a1.set(xlabel="node capacitance C_eff (pF)", ylabel="pedestal residual after linear cal (µV)",
           title="(b) residual pedestal against node capacitance")
    a1.legend(fontsize=6)

    a2 = ax[1, 0]
    for k, a in res["archs"].items():
        rows = [r for r in a["sweeps"]["c_node"] if "error" not in r]
        a2.loglog([r["summary"]["c_eff"] * 1e12 for r in rows],
                  [r["summary"]["droop_max"] for r in rows], marker="o", label=ARCH_NAMES[k])
    a2.set(xlabel="node capacitance C_eff (pF)", ylabel="worst droop (V/s), tt, 27 °C",
           title="(c) droop (switch + ESD leakage)")
    a2.legend(fontsize=7)

    a3 = ax[1, 1]
    names = list(res["archs"])
    x = np.arange(len(names))
    ref = [res["archs"][k]["nominal"]["judge"]["s10_t0.001"]["refresh_infidelity"] for k in names]
    xt = [res["archs"][k]["nominal"]["judge"]["s10_t0.001"]["crosstalk_infidelity"] for k in names]
    a3.bar(x - 0.2, np.maximum(ref, 1e-12), 0.4, label="refresh during the gate")
    a3.bar(x + 0.2, np.maximum(xt, 1e-12), 0.4, label="neighbour crosstalk, 1.2 V line swing")
    a3.set_yscale("log")
    a3.axhline(1e-3, color="k", lw=0.8)
    a3.axhline(1e-4, color="k", ls="--", lw=0.8)
    a3.set_xticks(x, names)
    a3.set(ylabel="added 1 - F (s = 10 dec/V)", title="(d) dynamic errors fed to the CZ model")
    a3.legend(fontsize=7)
    a4 = ax[2, 0]
    lad = ladder(res)
    names = list(lad)
    x = np.arange(len(names))
    for j, (key, lab) in enumerate((("nominal", "nominal"), ("best", "best circuit"),
                                    ("centred", "+ centred"), ("comp_0.1", "+ compensated, u = 10 %"))):
        a4.bar(x + (j - 1.5) * 0.2, [lad[k][key] for k in names], 0.2, label=lab)
    a4.set_yscale("log")
    a4.set_xticks(x, names)
    a4.set(ylabel="hold time (s), s = 10, 99.9 %", title="(e) droop mitigation ladder, 27 °C")
    a4.legend(fontsize=7)

    a5 = ax[2, 1]
    for k, a in res["archs"].items():
        rows = [r for r in a["sweeps"]["esd_area"] if "error" not in r]
        a5.loglog([max(r["config"]["esd_area"], 1) for r in rows], [r["summary"]["droop_max"] for r in rows],
                  marker="o", label=ARCH_NAMES[k])
    a5.set(xlabel="ESD diode area (µm², 0 plotted at 1)", ylabel="worst droop (V/s)",
           title="(f) ESD sets the floor once channel leakage is gone")
    a5.legend(fontsize=6)
    fig.tight_layout()
    fig.savefig(path, dpi=150)


def main():
    res = json.loads((OUT / "cells.json").read_text())
    write_md(res, OUT / "cells.md")
    plot(res, OUT / "cells.png")


if __name__ == "__main__":
    main()
