"""Tables and figure of the cryogenic study, from results/cryogenic.json and results/beall_check.json.

Run:  python studies/cryogenic_report.py      (seconds; writes results/cryogenic.md and results/cryogenic.png)
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from flow import cosim as C  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "results"
REF = "s10_t0.001"
WORST = "s33.69_t0.0001"
GMIN_FLOOR = 1e-18 * 1.8          # A: gmin (1e-18 S) x the largest node voltage, the leakage resolution
LIT_N = {"Darnas 2026 (drift only)": 1e7, "van Staveren 2025 (per DAC)": 1e4}
R_GRID = np.geomspace(1e-9, 1e3, 121)         # droop rate (V/s)


def ok(rows):
    return [r for r in rows if r and "error" not in r]


def by(rows, design, band, corner="tt"):
    for r in rows:
        if r["design"] == design and r["band"] == band and r["corner"] == corner:
            return r
    return None


def droop_budget(res, rec, key=REF):
    """Accumulated droop allowed (V): static spec - eps - |residual|, doubled by centring."""
    s = res["spec"][key]
    resid = rec["residual"] if rec and np.isfinite(rec["residual"]) else 0.0
    return C.hold_budget(s, resid, 0.1), s


def n_curves(res, rec, key=REF):
    bd, s = droop_budget(res, rec, key)
    cell = rec["cell"]
    hold = bd / R_GRID
    flat = np.array([C.n_max(h, cell, s, bd) for h in hold])
    tree = np.array([C.n_max(h, cell, s, bd, tree_lines(cell)["tree, met2 wire"]) for h in hold])
    return hold, flat, tree


def failed_v(r):
    bad = [f"{v:g}" for v, e in zip(r["v_hold"], r["track_error"]) if abs(e) >= 0.1e-3]
    return ("none" if not bad else ", ".join(bad) + " V")


def band_text(v):
    if v is None:
        return "PDK models"
    t = f"dV_T = +{v[0]:g} V, mu × {v[1]:g}"
    if len(v) > 4:
        t = f"nMOS {t}; pMOS dV_T = +{v[3]:g} V, mu × {v[4]:g}"
    return t


# Line variants for the sensitivity table. SKY130 metal 2 (magic sky130A.tech,
# extract style ngspice): 0.125 ohm/sq, area 17.5 aF/um^2, fringe 37.8 aF/um per edge. A 0.5 um line
# along a ~22 um cell pitch (500 um^2 cells): ~5.5 ohm and ~2.2 fF per electrode.
LINES = {
    "lumped": C.LineConfig(),
    "R_src 500 ohm": C.LineConfig(r_src=500.0),
    "R_src 5 kohm": C.LineConfig(r_src=5e3),
    "met2 wire, 0.5 um": C.LineConfig(r_wire_per=5.5, c_wire_per=2.2e-15),
    "met2 wire + R_src 500 ohm": C.LineConfig(r_src=500.0, r_wire_per=5.5, c_wire_per=2.2e-15),
}
TREE_BRANCH = 1000           # electrodes per leaf line of a tree demultiplexer


def tree_lines(cell):
    """Tree demux: each leaf line carries TREE_BRANCH switches (and their wire)."""
    base = 10e-12 + TREE_BRANCH * cell["c_line_cell"]
    return {"tree, lumped": C.LineConfig(c_line_fixed=base),
            "tree, met2 wire": C.LineConfig(c_line_fixed=base, r_wire_per=5.5, c_wire_per=2.2e-15),
            "tree, met2 wire + R_src 500 ohm": C.LineConfig(c_line_fixed=base, r_src=500.0, r_wire_per=5.5,
                                                         c_wire_per=2.2e-15)}


def fmt(x, unit=""):
    return "—" if x is None or not np.isfinite(x) else f"{x:.3g}{unit}"


def write_md(res, path):
    sw = ok(res["switching"])
    designs = list(res["designs"])
    bands = list(res["bands"])
    L = ["# Cryogenic results (generated by studies/cryogenic_report.py; do not edit)", "",
         "Cryogenic proxy on the SKY130 FET models (|V_T| + dV_T, mobility × mu, all bins), run at 27 °C. "
         "Bands: " + "; ".join(f"{b}: {band_text(v)}" for b, v in res["bands"].items()) + ". "
         "C_node = 1 pF. Reference point s = 10 dec/V, "
         "99.9 %; worst case s = 33.69 dec/V, 99.99 %.", "",
         "## 1. Switching under the temperature bands (tt)", "",
         "| design | band | held voltages NOT passed (track error ≥ 0.1 mV) | full range? | pedestal mean (mV) | residual (µV) | margin, worst case "
         "| refresh 1 − F | crosstalk 1 − F | τ_node (ns) | C_off (fF) |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for d in designs:
        for b in bands:
            r = by(sw, d, b)
            if not r:
                L.append(f"| {d} | {b} | simulation failed | | | | | | | | |")
                continue
            j = r["judge"]
            L.append(f"| {d} | {b} | {failed_v(r)} | {'yes' if r['passes_full_range'] else 'NO'} | "
                     f"{r['summary']['pedestal_mean'] * 1e3:.3g} | {r['residual'] * 1e6:.3g} | "
                     f"{j[WORST]['residual_margin']:.3g} | {j[REF]['refresh_infidelity']:.1e} | "
                     f"{j[REF]['crosstalk_infidelity']:.1e} | {r['cell']['tau_node'] * 1e9:.3g} | "
                     f"{r['cell']['c_line_cell'] * 1e15:.3g} |")
    L += ["", f"## 2. Process corners in the {res['bands'] and 'cryogenic proxy'} band (4 K proxy)", "",
          "| design | corner | highest V passed | residual (µV) | margin, worst case | refresh 1 − F | τ_node (ns) |",
          "|---|---|---|---|---|---|---|"]
    for d in designs:
        for c in ("tt", "ff", "ss", "fs", "sf"):
            r = by(sw, d, "4 K proxy", c)
            if r:
                L.append(f"| {d} | {c} | {r['v_pass_max']:g} V | {r['residual'] * 1e6:.3g} | "
                         f"{r['judge'][WORST]['residual_margin']:.3g} | {r['judge'][REF]['refresh_infidelity']:.1e} | "
                         f"{r['cell']['tau_node'] * 1e9:.3g} |")
    L += ["", "## 3. Leakage against temperature (PDK models; qualified to −40 °C only)", "",
          f"Values at or below the solver's leakage resolution (gmin × V ≈ {GMIN_FLOOR * 1e18:.1f} aA) are "
          "marked ≤.", "", "| design | " + " | ".join(f"{t:g} °C" for t in sorted({x['temp_c'] for x in ok(res['leakage'])}, reverse=True)) + " |",
          "|---|" + "---|" * len({x['temp_c'] for x in ok(res['leakage'])})]
    temps = sorted({x["temp_c"] for x in ok(res["leakage"])}, reverse=True)
    for d in designs:
        cells = []
        for t in temps:
            x = next((y for y in ok(res["leakage"]) if y["design"] == d and y["temp_c"] == t), None)
            if not x:
                cells.append("—")
            elif x["leakage_max"] <= 2 * GMIN_FLOOR:
                cells.append(f"≤ {2 * GMIN_FLOOR * 1e18:.0f} aA")
            else:
                cells.append(f"{x['leakage_max'] * 1e15:.3g} fA ({x['droop_max']:.2g} V/s)")
        L.append(f"| {d} | " + " | ".join(cells) + " |")
    L += ["", "Measured droop of cryo-CMOS chips (the 4 K anchors): " +
          "; ".join(f"{k}: {v:.2g} V/s" for k, v in res["anchors"].items()) + ".", ""]
    # 4. electrodes per line at the anchors
    L += ["## 4. Hold time and electrodes per line at the cryogenic droop anchors (4 K proxy switching, s = 10, 99.9 %)", "",
          "| design | droop budget (mV) | " + " | ".join(f"{k} ({v:.2g} V/s): hold / flat / tree" for k, v in res["anchors"].items()) + " |",
          "|---|---|" + "---|" * len(res["anchors"])]
    for d in designs:
        r = by(sw, d, "4 K proxy")
        if not r:
            continue
        bd, s = droop_budget(res, r)
        cells = []
        for v in res["anchors"].values():
            hold = bd / v
            nf = C.n_max(hold, r["cell"], s, bd)
            nt = C.n_max(hold, r["cell"], s, bd, C.LineConfig(c_line_fixed=10e-12 + 1000 * r["cell"]["c_line_cell"]))
            cells.append(f"{hold:.3g} s / {nf:.2g} / {nt:.2g}")
        L.append(f"| {d} | {bd * 1e3:.3g} | " + " | ".join(cells) + " |")
    L += ["", "## 5. ESD pulse distortion against temperature (TG, 1 pF, 100 µm² ESD pair, s = 10)", "",
          "| temperature | k range | worst 1 − F, per-electrode k | worst 1 − F, one global k |", "|---|---|---|---|"]
    for e in ok(res["esd_pulse"]):
        L.append(f"| {e['temp_c']:g} °C | {min(e['k']):.4f}-{max(e['k']):.4f} | {max(e['f_dyn']):.2e} | "
                 f"{max(e['f_dyn_global_k']):.2e} |")
    L += extra_sections(res, sw, designs)
    rr = res.get("relaxed_runs", [])
    L += ["", f"Decks that needed a retry (reltol 1e-4 or 50 ps maximum step): {len(rr)}.",
          f"Runtime of robustness.py: {res['runtime_s'] / 60:.0f} min.", ""]
    path.write_text("\n".join(L), encoding="utf-8")


def extra_sections(res, sw, designs):
    L = []
    # Beall 2026 cross-check
    bpath = OUT / "beall_check.json"
    if bpath.exists():
        b = json.loads(bpath.read_text())
        L += ["## 6. Cross-check of the proxy against the Beall 2026 77 K SKY130 models (LVT devices)", "",
              "Conductance error: RMS of ln(G) at |V_DS| = 10 mV over |V_GS| = 0.9-1.8 V (0.1 ≈ 10 %). V_T by constant "
              "current (0.1 µA · W/L). Proxy fits on a grid; the 'our 77 K band' row uses (+0.10 V, ×1.7) on both types.", "",
              "| device | V_T 300 K (PDK) | V_T 77 K (Beall model / measured) | G_on 77 K / 300 K (model) | proxy fit to model (dV_T, mu): error | "
              "proxy fit to measured: error | our 77 K band: error vs model | Beall model vs its data |", "|---|---|---|---|---|---|---|---|"]
        for name, r in b.items():
            pb, pm, pk = r["proxy_best"], r["proxy_fit_to_measured"], r["proxy_band_77K"]
            L.append(f"| {name} | {r['pdk_300K']['vt']:.3f} V | {r['beall_77K_model']['vt']:.3f} / "
                     f"{r['beall_77K_measured']['vt']:.3f} V | {r['beall_77K_model']['g_on'] / r['pdk_300K']['g_on']:.2f} | "
                     f"(+{pb['dvt']:g} V, ×{pb['mu']:g}): {pb['log_g_rms_vs_model']:.3f} | "
                     f"(+{pm['dvt']:g} V, ×{pm['mu']:g}): {pm['log_g_rms_vs_measured']:.3f} | "
                     f"{pk['log_g_rms_vs_model']:.3f} | {r['model_vs_measured_log_g_rms']:.3f} |")
        L.append("")
    # kickback
    kb = ok(res.get("kickback", []))
    if kb:
        L += ["## 7. OTA buffer kickback under the bands (T-switch + OTA, 1 pF, after a refresh at 0.9 V)", "",
              "| band | OTA current | shift after opening (µV) | settles to 10 µV in | final level − target (mV, removed by in-situ calibration) |",
              "|---|---|---|---|---|"]
        for k in kb:
            L.append(f"| {k['band']} | {k['i_buf'] * 1e9:g} nA | {k['kickback'] * 1e6:.0f} | {k['t_settle'] * 1e6:.2g} µs | "
                     f"{k['final_minus_target'] * 1e3:.2f} |")
        L.append("")
    # mismatch
    mm = ok(res.get("mismatch", []))
    if mm:
        rms_spec = res["spec"][WORST]
        L += ["## 8. V_T mismatch scaled at 4 K (4 K proxy; one calibration shared by all channels)", "",
              f"σ of the pedestal across Monte Carlo seeds, worst held voltage the switch passes. Margin = RMS spec "
              f"({rms_spec * 1e6:.0f} µV at s = 33.69, 99.99 %) / σ. The mismatch scale is a sensitivity: no SKY130 4 K "
              "mismatch data were found. With per-channel calibration (the paper's assumption) mismatch does not enter.", "",
              "| design | mismatch × 1 | × 1.5 | × 2 |", "|---|---|---|---|"]
        for d in sorted({x["design"] for x in mm}, key=designs.index):
            cells = []
            for f in (1.0, 1.5, 2.0):
                rows = [x for x in mm if x["design"] == d and x["mm"] == f]
                if len(rows) < 3:
                    cells.append("—")
                    continue
                ped = np.array([x["pedestal"] for x in rows])
                okv = np.all([x["ok"] for x in rows], axis=0)
                sig = float(ped[:, okv].std(axis=0).max()) if okv.any() else float("nan")
                cells.append(f"σ {sig * 1e6:.3g} µV, margin {rms_spec / sig:.3g} (n = {len(rows)})")
            L.append(f"| {d} | " + " | ".join(cells) + " |")
        L.append("")
    # line sensitivity
    L += ["## 9. Line model sensitivity: electrodes per flat line at the 4 K droop anchors (4 K proxy switching)", "",
          "Variants: DAC output resistance, and a distributed SKY130 met2 line (0.125 Ω/□, ~0.1 fF/µm for 0.5 µm "
          "width; ~5.5 Ω and ~2.2 fF per ~22 µm cell pitch). Distributed RC by Elmore (wire resistance counts half), "
          "checked against an RC ladder in tests/test_cosim.py.", ""]
    anchors = {"ESD-dominated 3.1 mV/s": 3.1e-3, "Darnas 5.5 µV/s": 5.5e-6}
    tnames = list(tree_lines({"c_line_cell": 0.0}))
    for an, v in anchors.items():
        L += [f"### Droop {an}", "", "| design | " + " | ".join(list(LINES) + tnames) + " |",
              "|---|" + "---|" * (len(LINES) + len(tnames))]
        for d in designs:
            r = by(sw, d, "4 K proxy")
            if not r:
                continue
            bd, s = droop_budget(res, r)
            lines = list(LINES.values()) + list(tree_lines(r["cell"]).values())
            cells = [f"{C.n_max(bd / v, r['cell'], s, bd, line):.2g}" for line in lines]
            L.append(f"| {d} | " + " | ".join(cells) + " |")
        L.append("")
    L.append("")
    return L


def plot(res, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    sw = ok(res["switching"])
    designs = list(res["designs"])
    bands = list(res["bands"])
    fig, ax = plt.subplots(2, 3, figsize=(17, 9.5))
    x = np.arange(len(designs))
    a = ax[0, 0]
    for j, b in enumerate(bands):
        y = [by(sw, d, b)["judge"][WORST]["residual_margin"] if by(sw, d, b) else np.nan for d in designs]
        bw = 0.8 / len(bands)
        a.bar(x + (j - (len(bands) - 1) / 2) * bw, y, bw, label=b)
    for c in ("ff", "ss", "fs", "sf"):
        y = [by(sw, d, "4 K proxy", c)["judge"][WORST]["residual_margin"] if by(sw, d, "4 K proxy", c) else np.nan
             for d in designs]
        a.plot(x + 0.1, y, "k_", ms=10, label="4 K proxy, corners" if c == "ff" else None)
    a.axhline(1, color="r", lw=0.8)
    a.set_yscale("log")
    a.set_xticks(x, designs, rotation=30, ha="right", fontsize=7)
    a.set(ylabel="residual-pedestal margin (s = 33.69, 99.99 %)", title="(a) static error under the bands")
    a.legend(fontsize=7)
    a = ax[0, 1]
    for j, b in enumerate(bands):
        y = [sum(abs(e) >= 0.1e-3 for e in by(sw, d, b)["track_error"]) if by(sw, d, b) else np.nan for d in designs]
        bw = 0.8 / len(bands)
        a.bar(x + (j - (len(bands) - 1) / 2) * bw, y, bw, label=b)
    a.set_xticks(x, designs, rotation=30, ha="right", fontsize=7)
    a.set(ylabel="held voltages not passed (of 7)",
          title="(b) range: NMOS loses its top, TG a dead band (pMOS shift)")
    a.legend(fontsize=7)
    a = ax[0, 2]
    temps = sorted({y["temp_c"] for y in ok(res["leakage"])})
    for d in designs:
        pts = [(y["temp_c"] + 273.15, y["leakage_max"]) for y in ok(res["leakage"]) if y["design"] == d]
        pts.sort()
        if pts:
            a.semilogy(*zip(*pts), "o-", label=d)
    a.axhline(2 * GMIN_FLOOR, color="grey", ls=":", label="solver resolution (gmin × V)")
    for k, v in res["anchors"].items():
        a.plot(4, v * 1e-12, "k*", ms=8)
    a.annotate("4 K anchors\n(droop × 1 pF)", (4, max(res["anchors"].values()) * 1e-12), fontsize=7,
               xytext=(15, 1e-14))
    a.set(xlabel="temperature (K)", ylabel="worst hold-node leakage (A)", xscale="log",
          title="(c) leakage: PDK trend and measured 4 K droop")
    a.legend(fontsize=6)
    a = ax[1, 0]
    for d in designs:
        r = by(sw, d, "4 K proxy")
        if r:
            bd, _ = droop_budget(res, r)
            a.loglog(R_GRID, bd / R_GRID, label=d)
    for k, v in res["anchors"].items():
        a.axvline(v, color="grey", lw=0.6, ls="--")
    a.set(xlabel="droop rate (V/s)", ylabel="hold time at 99.9 %, s = 10 (s)",
          title="(d) hold time; dashed: measured cryo-CMOS droop")
    a.legend(fontsize=6)
    a = ax[1, 1]
    for i, d in enumerate(designs):
        r = by(sw, d, "4 K proxy")
        if r:
            _, flat, tree = n_curves(res, r)
            a.loglog(R_GRID, np.maximum(flat, 0.5), color=f"C{i}", label=d)
            a.loglog(R_GRID, np.maximum(tree, 0.5), color=f"C{i}", ls=":")
    for k, v in res["anchors"].items():
        a.axvline(v, color="grey", lw=0.6, ls="--")
    for (k, v), ls in zip(LIT_N.items(), ("-.", (0, (1, 3)))):
        a.axhline(v, color="k", lw=0.8, ls=ls, label=k)
    a.set(xlabel="droop rate (V/s)", ylabel="electrodes per DAC line at 99.9 %",
          title="(e) per DAC line, 4 K proxy: solid flat (lumped), dotted tree + met2 wire", ylim=(0.5, 1e14))
    a.legend(fontsize=6)
    a = ax[1, 2]
    es = ok(res["esd_pulse"])
    xx = np.arange(len(es))
    a.bar(xx - 0.2, [max(e["f_dyn"]) for e in es], 0.4, label="per-electrode k")
    a.bar(xx + 0.2, [max(e["f_dyn_global_k"]) for e in es], 0.4, label="one global k")
    a.axhline(1e-3, color="k", lw=0.8)
    a.axhline(1e-4, color="k", ls="--", lw=0.8)
    a.set_yscale("log")
    a.set_xticks(xx, [f"{e['temp_c']:g} °C" for e in es])
    a.set(ylabel="worst 1 − F from pulse distortion", title="(f) ESD pulse distortion against temperature")
    a.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(path, dpi=150)


def main(name="cryogenic.json"):
    res = json.loads((OUT / name).read_text())
    suffix = "_quick" if "quick" in name else ""
    write_md(res, OUT / f"cryogenic{suffix}.md")
    plot(res, OUT / f"cryogenic{suffix}.png")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "cryogenic.json")
